test_that("geo_moran() uses projected coordinates as metres, not degrees", {
  skip_if_not_installed("sf")
  skip_if_not_installed("terra")
  meuse <- as.data.frame(terra::unwrap(readRDS(system.file("ex/meuse.rds", package = "terra"))))
  meuse$lz <- log(meuse$zinc)
  proj <- sf::st_as_sf(meuse, coords = c("x", "y"), crs = 28992)
  ll <- sf::st_transform(proj, 4326)
  m_sf <- geo_moran(proj, lz, nperm = 99, seed = 1)
  m_ll <- geo_moran(ll, lz, nperm = 99, seed = 1)
  m_df <- geo_moran(meuse, lz, lon = x, lat = y, nperm = 99, seed = 1)
  expect_equal(m_sf$statistic, m_ll$statistic, tolerance = 0.01)
  expect_equal(m_df$statistic, m_sf$statistic)
  expect_gt(m_sf$statistic, 0.1)
})
