test_that("presets are listed by kind", {
  all <- map_presets()
  expect_true(all(c("kind", "preset", "label") %in% names(all)))
  expect_true(all(c("water", "river", "town") %in% all$preset))
  expect_true(all(map_presets("line")$kind == "line"))
  expect_error(map_presets("blob"), "kind")
})

test_that("presets style layers and user arguments win", {
  skip_if_not_installed("sf")
  cantons <- sf::st_read(system.file("ex/lux.shp", package = "terra"), quiet = TRUE)
  m <- geo_map() |> map_polygons(cantons, preset = "water")
  ly <- m$layers[[1]]
  expect_equal(ly$const, "#A6CEE3")
  expect_equal(ly$look$border, "#4A90C2")
  expect_equal(ly$label, "Water")
  m2 <- geo_map() |> map_polygons(cantons, preset = "water", fill = "red", label = "Lakes")
  expect_equal(m2$layers[[1]]$const, "red")
  expect_equal(m2$layers[[1]]$label, "Lakes")
  b <- sf::st_cast(sf::st_boundary(cantons), "MULTILINESTRING")
  m3 <- geo_map() |> map_lines(b, preset = "railway")
  expect_equal(m3$layers[[1]]$look$linetype, "42")
  p <- suppressWarnings(sf::st_point_on_surface(cantons))
  m4 <- geo_map() |> map_points(p, preset = "peak")
  expect_equal(m4$layers[[1]]$look$shape, 24)
  expect_error(geo_map() |> map_lines(b, preset = "water"), "line presets")
  skip_if_not_installed("ggnewscale")
  expect_s3_class(map_build(m3), "ggplot")
})
