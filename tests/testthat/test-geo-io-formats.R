terra_ex <- function(f) {
  skip_if_not_installed("terra")
  skip_if_not_installed("sf")
  system.file("ex", f, package = "terra")
}

test_that("netCDF variables are listed and read by name or number", {
  nc <- terra_ex("nouragues.nc")
  lay <- geo_layers(nc)
  expect_true(all(c("t2m", "tp", "ssrd") %in% lay$var))
  expect_true(all(lay$layers == 48))
  t2m <- geo_read(nc, var = "t2m")
  expect_s4_class(t2m, "SpatRaster")
  expect_equal(terra::nlyr(t2m), 48)
  expect_false(anyNA(terra::time(t2m)))
  both <- geo_read(nc, var = c("t2m", "tp"))
  expect_equal(terra::nlyr(both), 96)
  expect_equal(terra::nlyr(geo_read(nc, var = 4)), 48)
  expect_error(geo_read(nc, var = "nope"), "geo_layers")
})

test_that("Sentinel-2 bands list, and separate band files stack", {
  s2 <- terra_ex("sent2_L2A_2024-08-24.tif")
  lay <- geo_layers(s2)
  expect_identical(lay$name, c("B02", "B03", "B04", "B08"))
  r <- terra::rast(s2)
  files <- file.path(tempdir(), paste0(names(r), ".tif"))
  for (i in seq_along(files)) terra::writeRaster(r[[i]], files[i], overwrite = TRUE)
  stack <- geo_read(files)
  expect_equal(terra::nlyr(stack), 4)
  expect_identical(names(stack), names(r))
  expect_equal(terra::values(stack), terra::values(r), ignore_attr = TRUE)
})

test_that("ENVI cubes with a .hdr header are detected", {
  s2 <- terra_ex("sent2_L2A_2024-08-24.tif")
  dat <- tempfile(fileext = ".dat")
  terra::writeRaster(terra::rast(s2), dat, filetype = "ENVI", overwrite = TRUE)
  expect_true(file.exists(sub("\\.dat$", ".hdr", dat)))
  envi <- geo_read(dat)
  expect_equal(terra::nlyr(envi), 4)
})

test_that("AutoCAD DXF layers are listed, filtered and given a CRS", {
  lux <- sf::st_read(terra_ex("lux.shp"), quiet = TRUE)
  lux <- sf::st_cast(lux[, "NAME_1"], "MULTILINESTRING")
  names(lux)[1] <- "Layer"
  dxf <- tempfile(fileext = ".dxf")
  sf::st_write(lux, dxf, driver = "DXF", quiet = TRUE)
  lay <- geo_layers(dxf)
  expect_setequal(lay$cad_layer, unique(lux$Layer))
  expect_equal(sum(lay$entities), nrow(suppressWarnings(sf::st_cast(lux, "LINESTRING"))))
  one <- geo_read(dxf, cad_layer = "Diekirch", crs = 4326)
  expect_true(all(one$Layer == "Diekirch"))
  expect_equal(sf::st_crs(one)$epsg, 4326L)
  expect_message(geo_read(dxf), "no coordinate system")
  expect_error(geo_read(dxf, cad_layer = "Mars", crs = 4326), "not found")
})

test_that("FlatGeobuf, GPX and multi-layer files round-trip", {
  lux <- sf::st_read(terra_ex("lux.shp"), quiet = TRUE)
  fgb <- tempfile(fileext = ".fgb")
  sf::st_write(lux, fgb, driver = "FlatGeobuf", quiet = TRUE)
  back <- geo_read(fgb)
  expect_equal(nrow(back), nrow(lux))
  pts <- suppressWarnings(sf::st_centroid(sf::st_geometry(lux)))
  gpx_pts <- sf::st_sf(name = lux$NAME_2, geometry = sf::st_transform(pts, 4326))
  gpx <- tempfile(fileext = ".gpx")
  sf::st_write(gpx_pts, gpx, driver = "GPX", layer = "waypoints", quiet = TRUE)
  lay <- geo_layers(gpx)
  expect_true("waypoints" %in% lay$layer)
  wp <- geo_read(gpx, layer = "waypoints")
  expect_equal(nrow(wp), nrow(lux))
})
